/** 라이어 게임 '바보 모드'에서 라이어에게 줄 비슷한 단어 (같은 주제의 다른 단어) */
export function similarWord(category: string, word: string, list: string[], random: () => number): string {
  const others = list.filter((w) => w !== word);
  return others.length ? others[Math.floor(random() * others.length)] : word;
}

/** 방장이 입력한 단어 목록을 쉼표·줄바꿈·공백 기준으로 나눈다 */
export function parseCustomWords(text: unknown): string[] {
  if (typeof text !== 'string') return [];
  return [...new Set(text.split(/[,\n、，]+/).map((w) => w.trim().slice(0, 20)).filter(Boolean))].slice(0, 300);
}
